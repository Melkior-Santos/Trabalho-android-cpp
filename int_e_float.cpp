#include <iostream>
using namespace std;

int main()
{
  //Int representa um número inteiro, abaixo seguem alguns jeitos de declarar ou atribuir um valor à uma variável
  int a = 5;
  int b = 2, c = -1;
  int d;
  d = a+b+c;

  cout << "Ints" << endl;
  cout << "a: " << a << endl;
  cout << "b: " << b << endl;
  cout << "c: " << c << endl;
  cout << "d: " << d << endl;

  cout << endl;

  //Floats em geral representam números com vírgula
  float e = 3.9;
  float f = -4.2, g = 2.3;
  float h;
  h = e*f*g;

  cout << "Floats" << endl;
  cout << "e: " << e << endl;
  cout << "f: " << f << endl;
  cout << "g: " << g << endl;
  cout << "h: " << h << endl;
 
  int e_int = e;
  cout << "e convertido para int: " << e_int << endl; //Note que e_int não possui parte decimal





  
}
